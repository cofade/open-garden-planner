"""The committed 3D benchmark / showcase plans load and stay current (Phase 17, L0).

``tests/fixtures/plans/bench_small.ogp`` is the beauty-board scene and
``bench_large.ogp`` the performance scene for every 3D package. Both are
generated by ``scripts/make_bench_plans.py`` through the real serializer; this
test pins that they load through ``ProjectManager``, still contain every object
class the 3D pipeline must render, and that regenerating them reproduces the
committed files (item ids are seeded, so procedural plant shapes stay stable).
"""

from __future__ import annotations

import importlib.util
import json
from collections import Counter
from pathlib import Path

import pytest

from open_garden_planner.core import ProjectManager
from open_garden_planner.core.object_types import ObjectType
from open_garden_planner.ui.canvas.canvas_scene import CanvasScene

REPO = Path(__file__).resolve().parents[2]
PLANS = REPO / "tests" / "fixtures" / "plans"


def _load(name: str) -> tuple[CanvasScene, ProjectManager]:
    scene = CanvasScene()
    pm = ProjectManager()
    pm.load(scene, PLANS / name)
    return scene, pm


def _types(scene: CanvasScene) -> Counter:
    return Counter(
        item.object_type for item in scene.items() if getattr(item, "object_type", None)
    )


class TestBenchSmall:
    def test_loads_with_location_and_canvas(self, qtbot) -> None:
        scene, pm = _load("bench_small.ogp")
        # the frost dates decide whether the 3D view shows fruit and flowers on a date
        # (the L0 spike's in_frost_free_season read them) — in the format the Location dialog writes
        assert pm.location == {"latitude": 52.52, "longitude": 13.405,
                               "frost_dates": {"last_spring_frost": "04-09",
                                               "first_fall_frost": "10-31"}}
        assert (scene.width_cm, scene.height_cm) == (2400.0, 1600.0)

    def test_contains_every_3d_object_class(self, qtbot) -> None:
        scene, _ = _load("bench_small.ogp")
        types = _types(scene)
        required = {
            ObjectType.HOUSE, ObjectType.ROOF_RIDGE, ObjectType.GREENHOUSE,
            ObjectType.GARAGE_SHED, ObjectType.PERGOLA, ObjectType.TRELLIS,
            ObjectType.RAISED_BED, ObjectType.CONTAINER_ROUND, ObjectType.GARDEN_BED,
            ObjectType.LAWN, ObjectType.TERRACE_PATIO, ObjectType.DRIVEWAY,
            ObjectType.POND_POOL, ObjectType.FENCE, ObjectType.WALL,
            ObjectType.HEDGE_POLYGON, ObjectType.PATH, ObjectType.TREE,
            ObjectType.SHRUB, ObjectType.PERENNIAL, ObjectType.TABLE_RECTANGULAR,
            ObjectType.CHAIR, ObjectType.BENCH, ObjectType.TRAMPOLINE,
        }
        assert required <= set(types), sorted(t.name for t in required - set(types))

    def test_house_ridge_is_linked_both_ways(self, qtbot) -> None:
        scene, _ = _load("bench_small.ogp")
        items = {str(i.item_id): i for i in scene.items() if hasattr(i, "item_id")}
        house = next(i for i in items.values() if getattr(i, "object_type", None) == ObjectType.HOUSE)
        ridge = items[house.metadata["ridge_item_id"]]
        assert ridge.object_type == ObjectType.ROOF_RIDGE
        assert ridge.metadata["owner_polygon_id"] == str(house.item_id)

    def test_planted_children_and_species(self, qtbot) -> None:
        scene, _ = _load("bench_small.ogp")
        items = {i.item_id: i for i in scene.items() if hasattr(i, "item_id")}
        plants = [
            i for i in items.values()
            if getattr(i, "object_type", None) in (ObjectType.TREE, ObjectType.SHRUB, ObjectType.PERENNIAL)
        ]
        assert len(plants) >= 50
        # every plant carries a bundled species record and a planting date
        for plant in plants:
            assert isinstance(plant.metadata.get("plant_species"), dict), plant.name
            assert plant.metadata["plant_instance"]["planting_date"] == "2026-04-15"
        # raised-bed vegetables are children of their bed
        bed_children = [p for p in plants if p.parent_bed_id is not None]
        assert len(bed_children) >= 25
        for child in bed_children:
            assert child.item_id in items[child.parent_bed_id].child_item_ids


class TestBenchLarge:
    def test_loads_at_performance_scale(self, qtbot) -> None:
        scene, _ = _load("bench_large.ogp")
        types = _types(scene)
        plants = types[ObjectType.TREE] + types[ObjectType.SHRUB] + types[ObjectType.PERENNIAL]
        assert sum(types.values()) >= 400
        assert plants >= 300


def test_generator_reproduces_committed_fixtures(qtbot, tmp_path) -> None:
    """Regenerating writes the same plans (modulo the save timestamp)."""
    spec = importlib.util.spec_from_file_location(
        "make_bench_plans", REPO / "scripts" / "make_bench_plans.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    import open_garden_planner.app.settings as app_settings

    store = (app_settings.ORGANIZATION_NAME, app_settings.APPLICATION_NAME)
    spec.loader.exec_module(module)
    # Importing the generator must not retarget this process's settings key: a
    # module-scope rebinding once took it over for the rest of the session.
    after = (app_settings.ORGANIZATION_NAME, app_settings.APPLICATION_NAME)
    assert after == store
    for name, build in (("bench_small.ogp", module.build_small), ("bench_large.ogp", module.build_large),
                        ("bench_built.ogp", module.build_built)):
        fresh = tmp_path / name
        module._save(build(), fresh)
        assert module._normalised(fresh) == module._normalised(PLANS / name), (
            f"{name} is stale — rerun scripts/make_bench_plans.py"
        )


def test_the_built_world_plan_holds_every_object_and_every_roof_style(qtbot) -> None:
    """bench_built.ogp (Phase 17 L4, #388) is the L4 board's scene: every L4 object kind,
    every path style at its own width, a house in each roof style, a deck, a stone
    terrace, a driveway, a pond and a lawn."""
    from open_garden_planner.core.object_types import PATH_FENCE_STYLES, PathFenceStyle
    from open_garden_planner.core.roof_style import ROOF_STYLES
    from open_garden_planner.core.scene3d.builders import OBJECT_KINDS, SURFACE_KINDS

    scene, _ = _load("bench_built.ogp")
    kinds = {item.object_type.name for item in scene.items() if getattr(item, "object_type", None)}
    assert kinds >= OBJECT_KINDS | SURFACE_KINDS
    styles = {item.path_fence_style for item in scene.items()
              if getattr(item, "object_type", None) is ObjectType.PATH}
    assert styles == {style for style, info in PATH_FENCE_STYLES.items() if info.category == "path"}
    widths = {item.path_fence_style: item.pen().widthF() for item in scene.items()
              if getattr(item, "object_type", None) is ObjectType.PATH}
    assert widths[PathFenceStyle.STEPPING_STONES] == PATH_FENCE_STYLES[PathFenceStyle.STEPPING_STONES].stroke_width
    roofs = {item.metadata.get("roof_style") for item in scene.items()
             if getattr(item, "object_type", None) in (ObjectType.HOUSE, ObjectType.GARAGE_SHED,
                                                        ObjectType.TOOL_SHED)}
    assert roofs == {None, *ROOF_STYLES} - {"gable"}  # the house's gable is the automatic one


def test_the_older_bench_plans_keep_their_path_widths(qtbot) -> None:
    """L4 gave paths real widths; bench_small and bench_large keep the ones they were
    made with, so every number measured on them stays measured on the same plan."""
    spec = importlib.util.spec_from_file_location("make_bench_plans_widths",
                                                  REPO / "scripts" / "make_bench_plans.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    for name in ("bench_small.ogp", "bench_large.ogp"):
        scene, _ = _load(name)
        for item in scene.items():
            if getattr(item, "object_type", None) is ObjectType.PATH:
                assert item.pen().widthF() == module.LEGACY_PATH_WIDTH_CM[item.path_fence_style], name


