"""Gate for the functional-requirements topic files and their generated index (#1036).

The requirements live in ``docs/functional-requirements/`` — one topic file per area, each
owning the ID prefixes in its front matter — and ``README.md`` there is generated by
``scripts/generate_doc_indexes.py``. These tests run that gate on the real tree and pin
each failure mode on a small tree of their own.
"""

from __future__ import annotations

import importlib.util
import re
import subprocess
import sys
from pathlib import Path
from types import ModuleType

import pytest

REPO = Path(__file__).resolve().parents[2]


def _load(name: str) -> ModuleType:
    scripts = str(REPO / "scripts")
    if scripts not in sys.path:
        sys.path.insert(0, scripts)
    spec = importlib.util.spec_from_file_location(name, REPO / "scripts" / f"{name}.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


gdi = _load("generate_doc_indexes")


def _topic(root: Path, rel: str, title: str, prefixes: list[str], body: str,
           *, front: str | None = None) -> Path:
    path = root / gdi.FR_DIR / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    if front is None:
        listed = ", ".join(f'"{p}"' for p in prefixes)
        front = f'title: "{title}"\nprefixes: [{listed}]'
    path.write_text(f"---\n{front}\n---\n\n# {title}\n\n{body}", encoding="utf-8")
    return path


def _tree(root: Path) -> Path:
    _topic(root, "canvas.md", "Canvas", ["FR-CANVAS", "FR-GRID"],
           "## Canvas\n\n- **FR-CANVAS-01**: Metric.\n- **FR-CANVAS-02** (#12): Zoom.\n"
           "  - a sub-point\n\n## Grid\n\n- **FR-GRID-01**: Grid.\n\nAcceptance: tests.\n")
    _topic(root, "3d/walk.md", "Walk", ["FR-3D-WALK"], "- **FR-3D-WALK-01**: Walk.\n")
    assert gdi.write_frs(root) == []
    return root


def _errors(root: Path) -> list[str]:
    return gdi.check_frs(root)


# --- the real tree ------------------------------------------------------------------------


def test_the_real_topic_files_and_index_pass_the_gate() -> None:
    assert (REPO / gdi.FR_INDEX).is_file()
    assert gdi.check_frs(REPO) == []


def test_the_single_file_record_is_gone() -> None:
    assert not (REPO / "docs" / "functional-requirements.md").exists()


def test_the_real_tree_keeps_its_known_ids() -> None:
    """A sample across files, forms and the IDs the move created; a lost file shows here."""
    topics, errors = gdi.load_topics(REPO)
    assert errors == []
    ids = {fid for topic in topics for fid in topic.ids}
    assert len(ids) >= 510
    for fid in ("FR-AGENT-12a", "FR-AGENT-27", "FR-STACK-10", "FR-3D-WS-01", "FR-ICON-3C-06",
                "FR-SUN-09", "FR-TIMELINE-01", "FR-OBJ-08", "FR-PLANT-26", "FR-UI-28"):
        assert fid in ids, fid


def _tracked_text_files() -> list[str]:
    tracked = subprocess.run(
        ["git", "ls-files", "-z"], cwd=REPO, check=True, capture_output=True
    ).stdout.decode("utf-8").split("\0")
    return [rel for rel in tracked if rel and Path(rel).suffix.lower() in
            {".md", ".py", ".toml", ".txt", ".json", ".yml", ".yaml"}]


#: Files that may still name the retired single file or its chapters: a mirror of GitHub
#: issue titles as filed, a dated audit snapshot, the migration itself, and test fixtures.
_HISTORY = {
    "tests/data/issue_registry.json",
    "docs/11-risks-and-technical-debt/audits/2026-10/audit-2026-10-metrics.json",
    "scripts/split_fr_record.py",
    "scripts/check_skill_citations.py",
    "tests/unit/test_skill_citations.py",
    "tests/unit/test_fr_topic_files.py",
}


def test_no_tracked_file_names_the_retired_single_file() -> None:
    """A permalink to a fixed commit (``blob/<sha>/…#L39``) still resolves there and is exempt,
    together with the link text that names it."""
    permalink = re.compile(
        r"(?:\[[^\]]*\]\()?[^\s()]*/blob/[0-9a-f]{40}/docs/functional-requirements\.md[^\s)]*\)?"
    )
    bad = []
    for rel in _tracked_text_files():
        if rel in _HISTORY or not (REPO / rel).exists():
            continue
        text = permalink.sub("", (REPO / rel).read_text(encoding="utf-8"))
        if "functional-requirements.md" in text:
            bad.append(rel)
    assert bad == []


def test_no_tracked_file_cites_an_old_chapter_number() -> None:
    """``FR-27`` or ``FR-1.2`` named a chapter of the single file; no chapter exists now."""
    chapter = re.compile(r"\bFR-\d+(?:\.\d+)?\b")
    bad = []
    for rel in _tracked_text_files():
        if rel in _HISTORY or not (REPO / rel).exists():
            continue
        for number, line in enumerate((REPO / rel).read_text(encoding="utf-8").splitlines(), 1):
            if chapter.search(line):
                bad.append(f"{rel}:{number}: {line.strip()[:80]}")
    assert bad == []


# --- the gate on a small tree -------------------------------------------------------------


def test_a_generated_tree_passes(tmp_path: Path) -> None:
    assert _errors(_tree(tmp_path)) == []


def test_the_index_lists_files_and_the_next_free_id(tmp_path: Path) -> None:
    index = (_tree(tmp_path) / gdi.FR_INDEX).read_text(encoding="utf-8")
    assert "| [canvas.md](canvas.md) | Canvas | FR-CANVAS, FR-GRID | 3 |" in index
    assert "| FR-CANVAS | [canvas.md](canvas.md) | 2 | FR-CANVAS-03 |" in index
    assert "| FR-3D-WALK | [3d/walk.md](3d/walk.md) | 1 | FR-3D-WALK-02 |" in index


def test_a_hand_edited_index_fails(tmp_path: Path) -> None:
    root = _tree(tmp_path)
    index = root / gdi.FR_INDEX
    index.write_text(index.read_text(encoding="utf-8") + "extra\n", encoding="utf-8")
    assert any("stale or was edited by hand" in e for e in _errors(root))


def test_a_new_requirement_without_regeneration_fails(tmp_path: Path) -> None:
    root = _tree(tmp_path)
    path = root / gdi.FR_DIR / "3d" / "walk.md"
    path.write_text(path.read_text(encoding="utf-8") + "- **FR-3D-WALK-02**: Run.\n",
                    encoding="utf-8")
    assert any("stale" in e for e in _errors(root))


def test_a_prefix_owned_by_two_files_fails(tmp_path: Path) -> None:
    root = _tree(tmp_path)
    _topic(root, "other.md", "Other", ["FR-GRID"], "- **FR-GRID-02**: Again.\n")
    assert any("prefix FR-GRID is owned by both" in e for e in _errors(root))


@pytest.mark.parametrize("second", ["canvas.md", "other.md"])
def test_an_id_defined_twice_fails(tmp_path: Path, second: str) -> None:
    root = _tree(tmp_path)
    if second == "other.md":
        _topic(root, "other.md", "Other", ["FR-CANVAS"], "- **FR-CANVAS-01**: Twice.\n")
    else:
        path = root / gdi.FR_DIR / "canvas.md"
        path.write_text(path.read_text(encoding="utf-8") + "- **FR-CANVAS-01**: Twice.\n",
                        encoding="utf-8")
    assert any("FR-CANVAS-01 is defined more than once" in e for e in _errors(root))


def test_an_id_with_a_foreign_prefix_fails(tmp_path: Path) -> None:
    root = _tree(tmp_path)
    _topic(root, "other.md", "Other", ["FR-OTHER"],
           "- **FR-OTHER-01**: Mine.\n- **FR-SNAP-01**: Not mine.\n")
    assert any("FR-SNAP-01 uses prefix FR-SNAP, which this file does not own" in e
               for e in _errors(root))


@pytest.mark.parametrize("line", [
    "- A requirement without an ID",
    "* Another one",
    "1. A numbered one",
])
def test_a_bullet_without_an_id_fails(tmp_path: Path, line: str) -> None:
    root = _tree(tmp_path)
    _topic(root, "other.md", "Other", ["FR-OTHER"], f"- **FR-OTHER-01**: Fine.\n\n{line}\n")
    assert any("requirement bullet without an ID" in e for e in _errors(root))


@pytest.mark.parametrize("line", [
    "- **FR-OTHER-02:** colon inside the bold",
    "  - **FR-OTHER-02**: nested in another bullet",
    "### FR-OTHER-02: a heading",
    "**FR-OTHER-02**: bold without a bullet",
])
def test_another_definition_form_fails(tmp_path: Path, line: str) -> None:
    root = _tree(tmp_path)
    _topic(root, "other.md", "Other", ["FR-OTHER"], f"- **FR-OTHER-01**: Fine.\n\n{line}\n")
    assert any("defines an ID in another form" in e for e in _errors(root))


def test_a_cross_reference_in_prose_is_no_definition(tmp_path: Path) -> None:
    root = _tree(tmp_path)
    _topic(root, "other.md", "Other", ["FR-OTHER"],
           "- **FR-OTHER-01**: Like FR-CANVAS-01, and **FR-GRID-01** too.\n"
           "  It follows FR-3D-WALK-01.\n")
    assert gdi.write_frs(root) == []
    assert _errors(root) == []


def test_a_bullet_inside_a_fence_is_not_a_requirement(tmp_path: Path) -> None:
    root = _tree(tmp_path)
    _topic(root, "other.md", "Other", ["FR-OTHER"],
           "- **FR-OTHER-01**: Fine.\n\n```\n- not a requirement\n```\n")
    assert gdi.write_frs(root) == []
    assert _errors(root) == []


def test_a_prefix_without_requirements_fails(tmp_path: Path) -> None:
    root = _tree(tmp_path)
    _topic(root, "other.md", "Other", ["FR-OTHER", "FR-EMPTY"], "- **FR-OTHER-01**: One.\n")
    assert any("prefix FR-EMPTY has no requirement" in e for e in _errors(root))


def test_the_h1_must_match_the_title(tmp_path: Path) -> None:
    root = _tree(tmp_path)
    path = _topic(root, "other.md", "Other", ["FR-OTHER"], "- **FR-OTHER-01**: One.\n")
    path.write_text(path.read_text(encoding="utf-8").replace("# Other", "# Else"),
                    encoding="utf-8")
    assert any("only H1, '# Other'" in e for e in _errors(root))


@pytest.mark.parametrize("rel", ["Other.md", "other_file.md", "a/b/deep.md"])
def test_a_bad_file_name_or_depth_fails(tmp_path: Path, rel: str) -> None:
    root = _tree(tmp_path)
    _topic(root, rel, "Other", ["FR-OTHER"], "- **FR-OTHER-01**: One.\n")
    assert any("a topic file is <kebab-case>.md" in e for e in _errors(root))


@pytest.mark.parametrize(("front", "message"), [
    ('title: "Other"', "missing required field 'prefixes'"),
    ('title: "Other"\nprefixes: []', "prefixes must be a non-empty list"),
    ('title: "Other"\nprefixes: ["FR-OTHER"]\nstatus: "x"', "unknown or malformed field"),
    ('title: "Other"\nprefixes: ["fr-other"]', "is not an FR prefix"),
    ('title: "Other"\nprefixes: ["FR-OTHER", "FR-OTHER"]', "lists one prefix twice"),
])
def test_malformed_front_matter_fails(tmp_path: Path, front: str, message: str) -> None:
    root = _tree(tmp_path)
    _topic(root, "other.md", "Other", [], "- **FR-OTHER-01**: One.\n", front=front)
    assert any(message in e for e in _errors(root)), _errors(root)


def test_check_skips_a_tree_without_the_folder(tmp_path: Path) -> None:
    """An ADR-only tree (the ADR tests' own) has no FR gate to run."""
    assert gdi.check_frs(tmp_path) == []
    assert gdi.write_frs(tmp_path) == []


def test_main_checks_both_indexes(tmp_path: Path) -> None:
    root = _tree(tmp_path)
    folder = root / "docs" / "09-architecture-decisions"
    folder.mkdir(parents=True)
    (folder / "ADR-001-a.md").write_text(
        '---\nid: ADR-001\ntitle: "A"\nstatus: "Accepted"\n---\n\n# ADR-001: A\n\n'
        "**Status**: Accepted\n", encoding="utf-8")
    assert gdi.main([], root=root) == 0
    assert gdi.main(["--check"], root=root) == 0
    (root / gdi.FR_INDEX).write_text("hand-edited\n", encoding="utf-8")
    assert gdi.main(["--check"], root=root) == 1
